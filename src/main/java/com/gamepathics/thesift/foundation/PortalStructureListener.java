package com.gamepathics.thesift.foundation;

import org.bukkit.Bukkit;
import org.bukkit.Location;
import org.bukkit.Material;
import org.bukkit.NamespacedKey;
import org.bukkit.World;
import org.bukkit.block.Block;
import org.bukkit.block.BlockState;
import org.bukkit.block.Lootable;
import org.bukkit.entity.Entity;
import org.bukkit.event.EventHandler;
import org.bukkit.event.EventPriority;
import org.bukkit.event.Listener;
import org.bukkit.event.world.StructureGrowEvent;
import org.bukkit.persistence.PersistentDataType;
import org.bukkit.plugin.java.JavaPlugin;

import java.util.HashSet;
import java.util.Set;

/**
 * Listens for portal structure generation and applies post-generation logic.
 * 
 * <p>The structures themselves are generated by the datapack (main_portal and 
 * abandoned_main_portal). This listener handles:
 * <ul>
 *   <li>Detecting when portal structures are placed</li>
 *   <li>Applying loot to chests in abandoned portals</li>
 *   <li>Marking portal blocks for interaction with AncientCityPortal</li>
 *   <li>Preventing duplicate structure detection</li>
 * </ul>
 */
final class PortalStructureListener implements Listener {
    private final JavaPlugin plugin;
    private final NamespacedKey portalMarkerKey;
    private final Set<String> processedStructures = new HashSet<>();

    PortalStructureListener(JavaPlugin plugin) {
        this.plugin = plugin;
        this.portalMarkerKey = new NamespacedKey(plugin, "portal_structure");
    }

    /**
     * Detects structure generation and applies post-processing.
     * Note: StructureGrowEvent is for trees/plants, not structures.
     * For actual structure detection, we use chunk load events and scan for portal blocks.
     */
    @EventHandler(priority = EventPriority.MONITOR, ignoreCancelled = true)
    public void onChunkLoad(org.bukkit.event.world.ChunkLoadEvent event) {
        if (!event.isNewChunk()) return;
        
        World world = event.getWorld();
        if (!world.getName().equals(SiftDimensionManager.DIMENSION_KEY.getKey())) return;
        
        // Scan chunk for portal structure blocks
        // This is a simplified approach - in production you'd want to optimize this
        Bukkit.getScheduler().runTaskLater(plugin, () -> {
            scanChunkForPortals(event.getChunk());
        }, 20L); // Delay to ensure structure is fully generated
    }

    private void scanChunkForPortals(org.bukkit.Chunk chunk) {
        World world = chunk.getWorld();
        int baseX = chunk.getX() << 4;
        int baseZ = chunk.getZ() << 4;
        
        // Look for distinctive portal blocks (e.g., custom portal blocks or specific patterns)
        // For now, we'll look for reinforced deepslate patterns that indicate portal frames
        for (int x = 0; x < 16; x++) {
            for (int z = 0; z < 16; z++) {
                for (int y = world.getMinHeight(); y < world.getMaxHeight(); y++) {
                    Block block = chunk.getBlock(x, y, z);
                    
                    // Check for portal-related blocks
                    if (isPortalBlock(block)) {
                        String key = baseX + x + "," + y + "," + baseZ + z;
                        if (processedStructures.add(key)) {
                            onPortalBlockPlaced(block);
                        }
                    }
                }
            }
        }
    }

    private boolean isPortalBlock(Block block) {
        Material type = block.getType();
        // Portal structures use specific blocks - adjust based on actual NBT content
        return type == Material.REINFORCED_DEEPSLATE || 
               type == Material.DEEPSLATE_TILES ||
               type == Material.DEEPSLATE;
    }

    private void onPortalBlockPlaced(Block block) {
        // Mark block as part of a portal structure
        if (block.getState() instanceof org.bukkit.block.TileState tileState) {
            tileState.getPersistentDataContainer().set(
                portalMarkerKey, 
                PersistentDataType.BYTE, 
                (byte) 1
            );
            tileState.update();
        }
        
        // Apply loot to chests if this is an abandoned portal
        if (block.getType() == Material.CHEST || block.getType() == Material.TRAPPED_CHEST) {
            if (block.getState() instanceof Lootable lootable) {
                // Set loot table for abandoned portal chests
                lootable.setLootTable(
                    Bukkit.getLootTable(new NamespacedKey("thesift", "chests/abandoned_portal"))
                );
                lootable.update();
            }
        }
    }

    /**
     * Checks if a location is near a portal structure.
     */
    public boolean isNearPortal(Location location) {
        World world = location.getWorld();
        if (world == null) return false;
        
        int radius = 16; // Check within 16 blocks
        for (int x = -radius; x <= radius; x++) {
            for (int y = -radius; y <= radius; y++) {
                for (int z = -radius; z <= radius; z++) {
                    Block block = world.getBlockAt(
                        location.getBlockX() + x,
                        location.getBlockY() + y,
                        location.getBlockZ() + z
                    );
                    
                    if (block.getState() instanceof org.bukkit.block.TileState tileState) {
                        if (tileState.getPersistentDataContainer().has(
                            portalMarkerKey, 
                            PersistentDataType.BYTE
                        )) {
                            return true;
                        }
                    }
                }
            }
        }
        return false;
    }
}
