package com.gamepathics.thesift.foundation;

import org.bukkit.Bukkit;
import org.bukkit.Chunk;
import org.bukkit.Location;
import org.bukkit.Material;
import org.bukkit.NamespacedKey;
import org.bukkit.World;
import org.bukkit.block.Block;
import org.bukkit.block.BlockState;
import org.bukkit.block.TileState;
import org.bukkit.event.EventHandler;
import org.bukkit.event.EventPriority;
import org.bukkit.event.Listener;
import org.bukkit.event.world.ChunkLoadEvent;
import org.bukkit.loot.Lootable;
import org.bukkit.persistence.PersistentDataType;
import org.bukkit.plugin.java.JavaPlugin;

import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Set;

/**
 * Listens for portal structure generation and applies post-generation logic.
 *
 * <p>The structures themselves are generated by the datapack (main_portal and
 * abandoned_main_portal). This listener handles:
 * <ul>
 *   <li>Detecting when portal structures are placed</li>
 *   <li>Applying loot to chests in abandoned portals</li>
 *   <li>Marking portal tile blocks for interaction with AncientCityPortal</li>
 *   <li>Preventing duplicate structure detection with bounded memory caching</li>
 * </ul>
 */
final class PortalStructureListener implements Listener {
    private static final int MAX_PROCESSED_ENTRIES = 4096;

    private final JavaPlugin plugin;
    private final NamespacedKey portalMarkerKey;
    private final NamespacedKey abandonedPortalLootKey;

    // Bounded LRU cache to prevent memory leaks from long-running servers
    private final Set<String> processedStructures = Collections.synchronizedSet(
            Collections.newSetFromMap(new LinkedHashMap<String, Boolean>(128, 0.75f, true) {
                @Override
                protected boolean removeEldestEntry(Map.Entry<String, Boolean> eldest) {
                    return size() > MAX_PROCESSED_ENTRIES;
                }
            })
    );

    PortalStructureListener(JavaPlugin plugin) {
        this.plugin = plugin;
        this.portalMarkerKey = new NamespacedKey(plugin, "portal_structure");
        this.abandonedPortalLootKey = new NamespacedKey("thesift", "chests/abandoned_portal");
    }

    /**
     * Detects structure generation and applies post-processing.
     */
    @EventHandler(priority = EventPriority.MONITOR, ignoreCancelled = true)
    public void onChunkLoad(ChunkLoadEvent event) {
        if (!event.isNewChunk()) return;

        World world = event.getWorld();
        if (!world.getName().equals(SiftDimensionManager.DIMENSION_KEY.getKey())) return;

        // Run delayed to ensure structures have completed generation
        Chunk chunk = event.getChunk();
        Bukkit.getScheduler().runTaskLater(plugin, () -> {
            if (chunk.isLoaded()) {
                scanChunkForPortals(chunk);
            }
        }, 20L);
    }

    private void scanChunkForPortals(Chunk chunk) {
        World world = chunk.getWorld();
        int baseX = chunk.getX() << 4;
        int baseZ = chunk.getZ() << 4;

        int minY = Math.max(world.getMinHeight(), -32);
        int maxY = Math.min(world.getMaxHeight(), 220);

        for (int x = 0; x < 16; x++) {
            for (int z = 0; z < 16; z++) {
                for (int y = minY; y < maxY; y++) {
                    Block block = chunk.getBlock(x, y, z);
                    Material type = block.getType();

                    if (isPortalCandidate(type)) {
                        String key = (baseX + x) + "," + y + "," + (baseZ + z);
                        if (processedStructures.add(key)) {
                            onPortalBlockPlaced(block);
                        }
                    }
                }
            }
        }
    }

    private static boolean isPortalCandidate(Material type) {
        return type == Material.REINFORCED_DEEPSLATE
                || type == Material.CHEST
                || type == Material.TRAPPED_CHEST;
    }

    private void onPortalBlockPlaced(Block block) {
        BlockState state = block.getState();

        // Apply loot to chests in abandoned portals if loot table not already set
        if (state instanceof Lootable lootable) {
            if (lootable.getLootTable() == null) {
                lootable.setLootTable(Bukkit.getLootTable(abandonedPortalLootKey));
                state.update();
            }
        }

        // Mark tile state if applicable
        if (state instanceof TileState tileState) {
            tileState.getPersistentDataContainer().set(portalMarkerKey, PersistentDataType.BYTE, (byte) 1);
            tileState.update();
        }
    }

    /**
     * Checks if a location is near a portal structure.
     * Uses fast type-checking before calling expensive getState().
     */
    public boolean isNearPortal(Location location) {
        World world = location.getWorld();
        if (world == null) return false;

        int radius = 16;
        int originX = location.getBlockX();
        int originY = location.getBlockY();
        int originZ = location.getBlockZ();

        for (int x = -radius; x <= radius; x++) {
            for (int y = -radius; y <= radius; y++) {
                for (int z = -radius; z <= radius; z++) {
                    Block block = world.getBlockAt(originX + x, originY + y, originZ + z);
                    // Fast path: Only TileStates can hold persistent data
                    Material mat = block.getType();
                    if (mat == Material.CHEST || mat == Material.TRAPPED_CHEST || mat == Material.REINFORCED_DEEPSLATE) {
                        if (block.getState() instanceof TileState tileState) {
                            if (tileState.getPersistentDataContainer().has(portalMarkerKey, PersistentDataType.BYTE)) {
                                return true;
                            }
                        }
                    }
                }
            }
        }
        return false;
    }
}
